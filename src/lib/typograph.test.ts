import { describe, expect, it } from 'vitest'

import { typograph, typographDeep } from './typograph'

const n = (s: string) => typograph(s).replaceAll('\u00a0', '_').replaceAll('\u2011', '~')
const NB = String.fromCharCode(0xa0)

describe('typograph', () => {
  it('привязывает короткие слова и предлоги к следующему', () => {
    expect(n('Реализуем проекты без компромиссов в материалах и исполнении')).toBe(
      'Реализуем проекты без_компромиссов в_материалах и_исполнении',
    )
    expect(n('мебель для интерьеров')).toBe('мебель для_интерьеров')
    expect(n('решение **для вашей клиники**')).toBe('решение **для_вашей клиники**')
  })

  it('не склеивает обычные слова', () => {
    expect(n('Пришлите проект — получите точный расчёт.')).toBe(
      'Пришлите проект_— получите точный расчёт.',
    )
    expect(n('сочетания конструкций нестандартными')).toBe('сочетания конструкций нестандартными')
    expect(n('Проекты')).toBe('Проекты')
  })

  it('частицы, тире, инициалы, числа, дефис', () => {
    expect(n('Так ли это нужно сейчас')).toBe('Так_ли_это нужно сейчас')
    expect(n('проект А. С. Пушкина здесь')).toBe('проект А._С._Пушкина здесь')
    expect(n('цена 1 500 000 рублей за всё')).toBe('цена 1_500_000_рублей за_всё')
    expect(n('по дизайн-проектам архитекторов')).toBe('по_дизайн~проектам архитекторов')
    expect(n('Мытищи. Проспект Астрахова')).toBe('Мытищи. Проспект Астрахова')
  })

  it('сохраняет крайние пробелы', () => {
    expect(n(' Корпуса из МДФ — наш стандарт')).toBe(' Корпуса из_МДФ_— наш стандарт')
  })

  it('не трогает адреса и ключи', () => {
    const v = typographDeep({
      href: '/a b',
      title: 'в доме',
      list: [{ src: 'x y', alt: 'и он' }],
      seo: { description: 'по дизайн-проектам' },
    })
    expect(v).toEqual({
      href: '/a b',
      title: 'в доме'.replace(' ', NB),
      list: [{ src: 'x y', alt: 'и он'.replace(' ', NB) }],
      seo: { description: 'по дизайн-проектам' },
    })
  })
})
